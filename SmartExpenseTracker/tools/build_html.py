"""Build the real-server browser bundle and the double-clickable website launcher.

Python 3 is needed only when changing frontend source. All generated assets ship
with the project. The launcher opens the Java website; accounts require its server.
"""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / 'dist'

def module_source(name):
    source = (DIST / name).read_text(encoding='utf-8')
    exports = re.findall(r'^export (?:async )?(?:const|function) (\w+)', source, re.M)
    imports = r'^import\s*\{([^}]+)\}\s*from\s*[\'\"]([^\'\"]+)[\'\"];[ \t]*\n'
    names = re.findall(imports, source, re.M)
    source = re.sub(imports, '', source, flags=re.M)
    source = re.sub(r'^export ', '', source, flags=re.M)
    prefix = ''.join('const {' + fields + '} = logic;\n' for fields, _ in names)
    return prefix + source, exports

logic, exports = module_source('logic.js')
app, _ = module_source('app.js')
bundle = ('/* Generated by tools/build_html.py. Edit source modules, then rebuild. */\n'
          '(() => {\n"use strict";\nconst logic = (() => {\n' + logic +
          '\nreturn {' + ','.join(exports) + '};\n})();\n' + app + '\n})();\n')
(DIST / 'bundle.js').write_text(bundle, encoding='utf-8')
(ROOT / 'index.html').write_text((ROOT / 'tools/launcher.html').read_text(encoding='utf-8'), encoding='utf-8')
print('Built database-backed app bundle and index.html website launcher.')
